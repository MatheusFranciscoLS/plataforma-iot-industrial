package com.industria.iot_core.migracoes;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * O banco do demo já tinha as tabelas quando o Flyway foi adotado (o Hibernate as criou).
 * Aqui o banco é preparado como era antes, e a migração precisa só marcar a versão 1 como feita,
 * sem tentar criar de novo as tabelas que já existem.
 */
class BancoJaExistenteTest {

    @Test
    void bancoComTabelasMasSemHistoricoRecebeApenasOMarcoDaVersao1() {
        DriverManagerDataSource dados = new DriverManagerDataSource("jdbc:h2:mem:existente;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate jdbc = new JdbcTemplate(dados);

        // Como o Hibernate deixou o banco antes do Flyway: tabelas e dados, sem flyway_schema_history
        jdbc.execute("CREATE TABLE usuario (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(50) NOT NULL UNIQUE, senha_hash VARCHAR(255) NOT NULL)");
        jdbc.execute("CREATE TABLE registro_sensor (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_maquina VARCHAR(255), timestamp BIGINT, temperatura_motor DOUBLE PRECISION, vibracao DOUBLE PRECISION, rpm INTEGER, data_recebimento TIMESTAMP(6))");
        jdbc.update("INSERT INTO usuario (nome, senha_hash) VALUES ('admin', 'hash-existente')");

        Flyway.configure()
                .dataSource(dados)
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("1")
                .load()
                .migrate();

        // Nada foi apagado nem recriado
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM usuario WHERE nome = 'admin'", Integer.class)).isEqualTo(1);
        // A versão 1 aparece como "baseline", não como script executado
        String tipo = jdbc.queryForObject("SELECT \"type\" FROM \"flyway_schema_history\" WHERE \"version\" = '1'", String.class);
        assertThat(tipo).isEqualTo("BASELINE");
    }
}
