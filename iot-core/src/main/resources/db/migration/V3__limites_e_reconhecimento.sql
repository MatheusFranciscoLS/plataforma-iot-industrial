-- Limites de alerta por máquina (quando não há linha aqui, vale o limite padrão da API)
-- e o reconhecimento de alertas (quem viu o alerta e quando).

CREATE TABLE limite_maquina (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_maquina  VARCHAR(50)      NOT NULL,
    tipo        VARCHAR(20)      NOT NULL,
    limite      DOUBLE PRECISION NOT NULL,
    CONSTRAINT uk_limite_maquina_tipo UNIQUE (id_maquina, tipo)
);

ALTER TABLE alerta ADD COLUMN reconhecido_por VARCHAR(50);
ALTER TABLE alerta ADD COLUMN reconhecido_em  TIMESTAMP(6);
