-- Esquema que o Hibernate criava sozinho até aqui (tabelas usuario e registro_sensor).
-- Em bancos que já têm essas tabelas, o Flyway marca esta versão como feita e não a executa
-- (spring.flyway.baseline-on-migrate=true). Em banco vazio, ela cria tudo.

CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(50)  NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL
);

CREATE TABLE registro_sensor (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_maquina        VARCHAR(255),
    timestamp         BIGINT,
    temperatura_motor DOUBLE PRECISION,
    vibracao          DOUBLE PRECISION,
    rpm               INTEGER,
    data_recebimento  TIMESTAMP(6)
);

CREATE INDEX idx_registro_sensor_timestamp ON registro_sensor (timestamp);
