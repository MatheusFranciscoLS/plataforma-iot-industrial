-- Alertas guardados no servidor: um registro cada vez que uma máquina passa de um limite
-- (temperatura ou vibração), para a lista de alertas não sumir quando a página é recarregada.

CREATE TABLE alerta (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_maquina     VARCHAR(50)      NOT NULL,
    timestamp      BIGINT           NOT NULL,
    tipo           VARCHAR(20)      NOT NULL,
    valor          DOUBLE PRECISION NOT NULL,
    limite         DOUBLE PRECISION NOT NULL,
    data_registro  TIMESTAMP(6)     NOT NULL
);

CREATE INDEX idx_alerta_timestamp ON alerta (timestamp);
