export const LOCALES = { pt: 'pt-BR', en: 'en-US' };

/** Procura o texto no idioma; se faltar, usa o português; se faltar também, devolve a própria chave. */
export function traduzir(idioma, chave, valores) {
  const texto = TEXTOS[idioma]?.[chave] ?? TEXTOS.pt[chave] ?? chave;
  if (!valores) return texto;
  return texto.replace(/\{(\w+)\}/g, (marca, nome) => (nome in valores ? String(valores[nome]) : marca));
}

/** Pacote de tradução de um idioma: a função t e o locale para números e horas. */
export function pacote(idioma) {
  return { idioma, t: (chave, valores) => traduzir(idioma, chave, valores), locale: LOCALES[idioma] };
}

export const I18N_PT = pacote('pt');
